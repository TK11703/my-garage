UPDATE vehicles
SET vin             = @Vin,
    make            = @Make,
    model           = @Model,
    trim            = @Trim,
    year            = @Year,
    vehicle_type_id = @VehicleTypeId,
    ownership       = @Ownership,
    purchased_on    = @PurchasedOn,
    lease_ends_on   = @LeaseEndsOn,
    engine          = @Engine,
    horsepower      = @Horsepower,
    fuel_type_id    = @FuelTypeId,
    transmission_id = @TransmissionId,
    mileage         = @Mileage,
    latest_odometer_reading = @LatestOdometerReading,
    color           = @Color,
    seats           = @Seats,
    doors           = @Doors,
    drivetrain_id   = @DrivetrainId,
    wheel_size      = @WheelSize,
    tire_size       = @TireSize,
    updated_at      = @UpdatedAt,
    updated_by      = @UpdatedBy
WHERE id = @Id
  AND owner_id = @OwnerId;
